import { readdir, readFile, rm, writeFile } from "node:fs/promises";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const SCHEMAS_DIR = new URL("../../../contracts/schemas/", import.meta.url);
const OUT_DIR = new URL("../src/contracts/", import.meta.url);
const SCHEMA_SUFFIX = ".schema.json";
const GENERATED_SUFFIX = ".gen.ts";

interface Contract {
  readonly name: string;
  readonly typeName: string;
  readonly schemaName: string;
  readonly schema: JSONSchema;
}

function toContract(name: string, schema: JSONSchema): Contract {
  const typeName = name.replace(/(^|_)([a-z])/g, (_match, _sep: string, letter: string) =>
    letter.toUpperCase(),
  );
  const schemaName = `${typeName.charAt(0).toLowerCase()}${typeName.slice(1)}Schema`;
  return { name, typeName, schemaName, schema };
}

function banner(source: string): string {
  return `// Generated by \`npm run gen:contracts\` from ${source}. Do not edit.`;
}

async function loadContracts(): Promise<Contract[]> {
  const files = (await readdir(SCHEMAS_DIR)).filter((file) => file.endsWith(SCHEMA_SUFFIX)).sort();
  return Promise.all(
    files.map(async (file) => {
      const text = await readFile(new URL(file, SCHEMAS_DIR), "utf8");
      return toContract(file.slice(0, -SCHEMA_SUFFIX.length), JSON.parse(text) as JSONSchema);
    }),
  );
}

// json-schema-to-typescript reads tuples only from the draft-07 `items: [...]` form.
function withDraft7Tuples(node: unknown): unknown {
  if (Array.isArray(node)) {
    return node.map(withDraft7Tuples);
  }
  if (typeof node !== "object" || node === null) {
    return node;
  }
  const entries = Object.entries(node).map(([key, value]) => [
    key === "prefixItems" ? "items" : key,
    withDraft7Tuples(value),
  ]);
  return Object.fromEntries(entries);
}

async function shapeModule(contract: Contract): Promise<string> {
  const { name, typeName, schemaName, schema } = contract;
  const forTypes = withDraft7Tuples({ ...schema, title: typeName }) as JSONSchema;
  const types = await compile(forTypes, typeName, {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
    style: { printWidth: 100 },
  });
  return [
    banner(`contracts/schemas/${name}${SCHEMA_SUFFIX}`),
    `import { ContractValidator } from "./ContractValidator.js";`,
    "",
    types.trim(),
    "",
    `export const ${schemaName} = ${JSON.stringify(schema, null, 2)};`,
    "",
    `const validator = new ContractValidator<${typeName}>("${name}", ${schemaName});`,
    "",
    `export function validate${typeName}(value: unknown): ${typeName} {`,
    "  return validator.validate(value);",
    "}",
    "",
  ].join("\n");
}

function indexModule(contracts: readonly Contract[]): string {
  const lines = contracts.map(
    ({ name, typeName, schemaName }) =>
      `export { type ${typeName}, ${schemaName}, validate${typeName} } from "./${name}.gen.js";`,
  );
  const imports = contracts.map(
    ({ name, typeName }) => `import { validate${typeName} } from "./${name}.gen.js";`,
  );
  const entries = contracts.map(({ name, typeName }) => `  ${name}: validate${typeName},`);
  return [
    banner("contracts/schemas"),
    ...imports,
    "",
    ...lines,
    "",
    "export const CONTRACT_VALIDATORS = {",
    ...entries,
    "} as const;",
    "",
    "export type ContractName = keyof typeof CONTRACT_VALIDATORS;",
    "",
  ].join("\n");
}

async function removeStale(): Promise<void> {
  const stale = (await readdir(OUT_DIR)).filter((file) => file.endsWith(GENERATED_SUFFIX));
  await Promise.all(stale.map((file) => rm(new URL(file, OUT_DIR))));
}

async function main(): Promise<void> {
  const contracts = await loadContracts();
  await removeStale();
  for (const contract of contracts) {
    const path = new URL(`${contract.name}${GENERATED_SUFFIX}`, OUT_DIR);
    await writeFile(path, await shapeModule(contract));
  }
  await writeFile(new URL(`index${GENERATED_SUFFIX}`, OUT_DIR), indexModule(contracts));
  console.log(`Generated ${contracts.length} contract modules in src/contracts/`);
}

await main();
